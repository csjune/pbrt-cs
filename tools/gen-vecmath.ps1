# Generates src/Pbrt/Util/VecMath.Tuples.g.cs: the repetitive parts of
# pbrt-v4's Tuple2/Tuple3 templates (util/vecmath.h) instantiated as concrete
# C# structs (C# has no template-template parameters or decltype-based
# return types). Type-specific code lives in VecMath.cs.
#
# Usage: pwsh tools/gen-vecmath.ps1
#
# NOTE: PowerShell variables are case-insensitive ($T and $t are the same).

param([string]$Out = (Join-Path $PSScriptRoot '../src/Pbrt/Util/VecMath.Tuples.g.cs'))

$ErrorActionPreference = 'Stop'

function Comps([int]$dim) { if ($dim -eq 2) { @('x', 'y') } else { @('x', 'y', 'z') } }

# Expands $pat once per component ('@' -> component name), joined by $sep.
function J([int]$dim, [string]$pat, [string]$sep = ', ') {
    (Comps $dim | ForEach-Object { $pat.Replace('@', $_) }) -join $sep
}

# Tuple types. Kind: Vector | Point | Normal. Vec: the matching vector type
# for Point arithmetic. PMinusP: result of Point - Point (pbrt's Point3fi
# returns Point3fi rather than a vector).
$tuples = @(
    @{ N = 'Vector2f';  Kind = 'Vector'; Dim = 2; T = 'Float' }
    @{ N = 'Vector2i';  Kind = 'Vector'; Dim = 2; T = 'int' }
    @{ N = 'Vector3f';  Kind = 'Vector'; Dim = 3; T = 'Float' }
    @{ N = 'Vector3i';  Kind = 'Vector'; Dim = 3; T = 'int' }
    @{ N = 'Vector3fi'; Kind = 'Vector'; Dim = 3; T = 'Interval' }
    @{ N = 'Point2f';   Kind = 'Point';  Dim = 2; T = 'Float';    Vec = 'Vector2f';  PMinusP = 'Vector2f' }
    @{ N = 'Point2i';   Kind = 'Point';  Dim = 2; T = 'int';      Vec = 'Vector2i';  PMinusP = 'Vector2i' }
    @{ N = 'Point3f';   Kind = 'Point';  Dim = 3; T = 'Float';    Vec = 'Vector3f';  PMinusP = 'Vector3f' }
    @{ N = 'Point3i';   Kind = 'Point';  Dim = 3; T = 'int';      Vec = 'Vector3i';  PMinusP = 'Vector3i' }
    @{ N = 'Point3fi';  Kind = 'Point';  Dim = 3; T = 'Interval'; Vec = 'Vector3fi'; PMinusP = 'Point3fi' }
    @{ N = 'Normal3f';  Kind = 'Normal'; Dim = 3; T = 'Float' }
)

# Explicit converting constructors (pbrt's `template <typename U> explicit
# Foo(Bar<U>)`), component-wise casts.
$conversions = @{
    'Vector2f' = @('Vector2i', 'Point2f', 'Point2i')
    'Vector2i' = @('Vector2f', 'Point2i', 'Point2f')
    'Vector3f' = @('Vector3i', 'Point3f', 'Point3i', 'Normal3f')
    'Vector3i' = @('Vector3f', 'Point3i', 'Point3f')
    'Point2f'  = @('Point2i', 'Vector2f', 'Vector2i')
    'Point2i'  = @('Point2f', 'Vector2i', 'Vector2f')
    'Point3f'  = @('Point3i', 'Vector3f', 'Vector3i')
    'Point3i'  = @('Point3f', 'Vector3i', 'Vector3f')
    'Normal3f' = @('Vector3f')
}

$bounds = @(
    @{ N = 'Bounds2f'; Dim = 2; T = 'Float'; P = 'Point2f'; V = 'Vector2f'; Lowest = 'Float.MinValue'; Max = 'Float.MaxValue'; Other = 'Bounds2i' }
    @{ N = 'Bounds2i'; Dim = 2; T = 'int';   P = 'Point2i'; V = 'Vector2i'; Lowest = 'int.MinValue';   Max = 'int.MaxValue';   Other = 'Bounds2f' }
    @{ N = 'Bounds3f'; Dim = 3; T = 'Float'; P = 'Point3f'; V = 'Vector3f'; Lowest = 'Float.MinValue'; Max = 'Float.MaxValue'; Other = 'Bounds3i' }
    @{ N = 'Bounds3i'; Dim = 3; T = 'int';   P = 'Point3i'; V = 'Vector3i'; Lowest = 'int.MinValue';   Max = 'int.MaxValue';   Other = 'Bounds3f' }
)

$sb = [System.Text.StringBuilder]::new()
function L([string]$s = '') { [void]$sb.AppendLine($s) }

L '// <auto-generated> by tools/gen-vecmath.ps1. Do not edit by hand. </auto-generated>'
L '//'
L '// pbrt is Copyright(c) 1998-2020 Matt Pharr, Wenzel Jakob, and Greg Humphreys.'
L '// The pbrt source code is licensed under the Apache License, Version 2.0.'
L '// SPDX: Apache-2.0'
L '//'
L '// Tuple2/Tuple3 and Bounds2/Bounds3 from src/pbrt/util/vecmath.h,'
L '// instantiated as concrete structs.'
L ''
L '#nullable enable'
L ''
L 'namespace Pbrt;'
L ''

foreach ($spec in $tuples) {
    $N = $spec.N; $T = $spec.T; $d = $spec.Dim
    $params = J $d "$T @"
    $isInterval = $T -eq 'Interval'
    $scalars = if ($isInterval) { @('Interval', 'Float') } else { @($T) }

    L "public partial struct $N : IEquatable<$N>"
    L '{'
    L "    // $($spec.Kind)$d Public Members"
    L "    public $T $(J $d '@');"
    L ''
    L "    public const int nDimensions = $d;"
    L ''
    L "    // $($spec.Kind)$d Public Methods"
    L '    [MethodImpl(MethodImplOptions.AggressiveInlining)]'
    L "    public $N($params)"
    L '    {'
    L (J $d '        this.@ = @;' "`n")
    L '        DCHECK(!HasNaN());'
    L '    }'
    L ''
    L "    public readonly bool HasNaN() => $(J $d 'IsNaN(@)' ' || ');"
    L ''
    L "    public $T this[int i]"
    L '    {'
    L '        [MethodImpl(MethodImplOptions.AggressiveInlining)]'
    L '        readonly get'
    L '        {'
    L "            DCHECK(i >= 0 && i <= $($d - 1));"
    if ($d -eq 2) { L '            return (i == 0) ? x : y;' }
    else { L '            if (i == 0) return x;'; L '            if (i == 1) return y;'; L '            return z;' }
    L '        }'
    L '        [MethodImpl(MethodImplOptions.AggressiveInlining)]'
    L '        set'
    L '        {'
    L "            DCHECK(i >= 0 && i <= $($d - 1));"
    if ($d -eq 2) { L '            if (i == 0) x = value; else y = value;' }
    else { L '            if (i == 0) x = value; else if (i == 1) y = value; else z = value;' }
    L '        }'
    L '    }'
    L ''

    # Additive operators
    switch ($spec.Kind) {
        'Point' {
            $V = $spec.Vec; $PmP = $spec.PMinusP
            L "    public static $N operator +($N a, $N b) => new($(J $d 'a.@ + b.@'));"
            L "    public static $N operator +($N p, $V v) => new($(J $d 'p.@ + v.@'));"
            L "    public static $N operator -($N p, $V v) => new($(J $d 'p.@ - v.@'));"
            L "    public static $PmP operator -($N a, $N b) => new($(J $d 'a.@ - b.@'));"
        }
        default {
            L "    public static $N operator +($N a, $N b) => new($(J $d 'a.@ + b.@'));"
            L "    public static $N operator -($N a, $N b) => new($(J $d 'a.@ - b.@'));"
        }
    }
    L "    public static $N operator -($N v) => new($(J $d '-v.@'));"
    L ''
    foreach ($S in $scalars) {
        L "    public static $N operator *($N v, $S s) => new($(J $d 's * v.@'));"
        L "    public static $N operator *($S s, $N v) => new($(J $d 's * v.@'));"
        if ($S -eq 'Interval') {
            L "    public static $N operator /($N v, $S d) => new($(J $d 'v.@ / d'));"
        } else {
            L "    public static $N operator /($N v, $S d)"
            L '    {'
            L '        DCHECK(d != 0);'
            L "        return new($(J $d 'v.@ / d'));"
            L '    }'
        }
    }
    L ''
    L "    public static bool operator ==($N a, $N b) => $(J $d 'a.@ == b.@' ' && ');"
    L "    public static bool operator !=($N a, $N b) => !(a == b);"
    L "    public readonly bool Equals($N other) => this == other;"
    L "    public override readonly bool Equals(object? obj) => obj is $N other && this == other;"
    L "    public override readonly int GetHashCode() => HashCode.Combine($(J $d '@'));"
    if ($isInterval) {
        L "    public override readonly string ToString() => `$`"[ $(J $d '{@}' ' ') ]`";"
    } elseif ($T -eq 'Float') {
        # pbrt's StringPrintf() formats floats with FloatToString().
        L "    public override readonly string ToString() => `$`"[ $(J $d '{FloatToString(@)}') ]`";"
    } else {
        L "    public override readonly string ToString() => FormattableString.Invariant(`$`"[ $(J $d '{@}') ]`");"
    }

    if ($conversions.ContainsKey($N)) {
        L ''
        foreach ($src in $conversions[$N]) {
            L "    public $N($src v) : this($(J $d "($T)v.@")) { }"
        }
    }
    L '}'
    L ''
}

# Free functions on tuples (Tuple2/Tuple3 Inline Functions)
L 'public static partial class Util'
L '{'
foreach ($spec in $tuples) {
    $N = $spec.N; $T = $spec.T; $d = $spec.Dim
    if ($T -eq 'Interval') { continue }
    $abs = if ($T -eq 'Float') { 'FMath.Abs' } else { 'Math.Abs' }
    L "    // $N Inline Functions"
    L "    public static $N Abs($N t) => new($(J $d "$abs(t.@)"));"
    if ($T -eq 'Float') {
        L "    public static $N Ceil($N t) => new($(J $d 'FMath.Ceiling(t.@)'));"
        L "    public static $N Floor($N t) => new($(J $d 'FMath.Floor(t.@)'));"
        L "    public static $N Lerp(Float t, $N t0, $N t1) => (1 - t) * t0 + t * t1;"
        L "    public static $N FMA(Float a, $N b, $N c) => new($(J $d 'FMA(a, b.@, c.@)'));"
        L "    public static $N FMA($N a, Float b, $N c) => FMA(b, a, c);"
    }
    L "    public static $N Min($N t0, $N t1) => new($(J $d 'Min(t0.@, t1.@)'));"
    L "    public static $N Max($N t0, $N t1) => new($(J $d 'Max(t0.@, t1.@)'));"
    if ($d -eq 2) {
        L "    public static $T MinComponentValue($N t) => Min(t.x, t.y);"
        L "    public static int MinComponentIndex($N t) => (t.x < t.y) ? 0 : 1;"
        L "    public static $T MaxComponentValue($N t) => Max(t.x, t.y);"
        L "    public static int MaxComponentIndex($N t) => (t.x > t.y) ? 0 : 1;"
    } else {
        L "    public static $T MinComponentValue($N t) => Min(t.x, Min(t.y, t.z));"
        L "    public static int MinComponentIndex($N t) => (t.x < t.y) ? ((t.x < t.z) ? 0 : 2) : ((t.y < t.z) ? 1 : 2);"
        L "    public static $T MaxComponentValue($N t) => Max(t.x, Max(t.y, t.z));"
        L "    public static int MaxComponentIndex($N t) => (t.x > t.y) ? ((t.x > t.z) ? 0 : 2) : ((t.y > t.z) ? 1 : 2);"
    }
    $perm = if ($d -eq 2) { 't[p[0]], t[p[1]]' } else { 't[p[0]], t[p[1]], t[p[2]]' }
    L "    public static $N Permute($N t, ReadOnlySpan<int> p) => new($perm);"
    L "    public static $T HProd($N t) => $(J $d 't.@' ' * ');"
    L ''
}
L '}'
L ''

foreach ($b in $bounds) {
    $N = $b.N; $T = $b.T; $P = $b.P; $V = $b.V; $d = $b.Dim
    L "public partial struct $N : IEquatable<$N>"
    L '{'
    L "    // Bounds$d Public Members"
    L "    public $P pMin, pMax;"
    L ''
    L "    // Bounds$d Public Methods"
    L "    // NOTE: new $N() is empty (pMin > pMax) like pbrt's default constructor,"
    L "    // but default($N) is the degenerate box at the origin."
    L "    public $N()"
    L '    {'
    L "        $T minNum = $($b.Lowest);"
    L "        $T maxNum = $($b.Max);"
    L "        pMin = new $P($(J $d 'maxNum'));"
    L "        pMax = new $P($(J $d 'minNum'));"
    L '    }'
    L ''
    L "    public $N($P p)"
    L '    {'
    L '        pMin = pMax = p;'
    L '    }'
    L ''
    L "    public $N($P p1, $P p2)"
    L '    {'
    L '        pMin = Min(p1, p2);'
    L '        pMax = Max(p1, p2);'
    L '    }'
    L ''
    L "    public $N($($b.Other) b)"
    L '    {'
    L '        if (b.IsEmpty())'
    L '            // Be careful about overflowing float->int conversions and the'
    L '            // like.'
    L "            this = new $N();"
    L '        else'
    L '        {'
    L "            pMin = new $P(b.pMin);"
    L "            pMax = new $P(b.pMax);"
    L '        }'
    L '    }'
    L ''
    L "    public $P this[int i]"
    L '    {'
    L '        [MethodImpl(MethodImplOptions.AggressiveInlining)]'
    L '        readonly get'
    L '        {'
    L '            DCHECK(i == 0 || i == 1);'
    L '            return (i == 0) ? pMin : pMax;'
    L '        }'
    L '        set'
    L '        {'
    L '            DCHECK(i == 0 || i == 1);'
    L '            if (i == 0) pMin = value; else pMax = value;'
    L '        }'
    L '    }'
    L ''
    if ($d -eq 2) {
        L "    public readonly $P Corner(int corner)"
        L '    {'
        L '        DCHECK(corner >= 0 && corner < 4);'
        L "        return new $P(this[corner & 1].x, this[(corner & 2) != 0 ? 1 : 0].y);"
        L '    }'
    } else {
        L "    public readonly $P Corner(int corner)"
        L '    {'
        L '        DCHECK(corner >= 0 && corner < 8);'
        L "        return new $P(this[corner & 1].x, this[(corner & 2) != 0 ? 1 : 0].y,"
        L "                      this[(corner & 4) != 0 ? 1 : 0].z);"
        L '    }'
    }
    L ''
    L "    public readonly $V Diagonal() => pMax - pMin;"
    L ''
    if ($d -eq 2) {
        L "    public readonly $T Area()"
        L '    {'
        L "        $V d = pMax - pMin;"
        L '        return d.x * d.y;'
        L '    }'
        L ''
        L '    public readonly int MaxDimension()'
        L '    {'
        L "        $V diag = Diagonal();"
        L '        if (diag.x > diag.y)'
        L '            return 0;'
        L '        else'
        L '            return 1;'
        L '    }'
    } else {
        L "    public readonly $T SurfaceArea()"
        L '    {'
        L "        $V d = Diagonal();"
        L '        return 2 * (d.x * d.y + d.x * d.z + d.y * d.z);'
        L '    }'
        L ''
        L "    public readonly $T Volume()"
        L '    {'
        L "        $V d = Diagonal();"
        L '        return d.x * d.y * d.z;'
        L '    }'
        L ''
        L '    public readonly int MaxDimension()'
        L '    {'
        L "        $V d = Diagonal();"
        L '        if (d.x > d.y && d.x > d.z)'
        L '            return 0;'
        L '        else if (d.y > d.z)'
        L '            return 1;'
        L '        else'
        L '            return 2;'
        L '    }'
    }
    L ''
    L "    public readonly bool IsEmpty() => $(J $d 'pMin.@ >= pMax.@' ' || ');"
    L "    public readonly bool IsDegenerate() => $(J $d 'pMin.@ > pMax.@' ' || ');"
    L ''
    L "    public static bool operator ==($N a, $N b) => a.pMin == b.pMin && a.pMax == b.pMax;"
    L "    public static bool operator !=($N a, $N b) => !(a == b);"
    L "    public readonly bool Equals($N other) => this == other;"
    L "    public override readonly bool Equals(object? obj) => obj is $N other && this == other;"
    L '    public override readonly int GetHashCode() => HashCode.Combine(pMin, pMax);'
    L '    public override readonly string ToString() => $"[ {pMin} - {pMax} ]";'
    L '}'
    L ''
}

# Free functions on bounds (Bounds2/Bounds3 Inline Functions)
L 'public static partial class Util'
L '{'
foreach ($b in $bounds) {
    $N = $b.N; $T = $b.T; $P = $b.P; $V = $b.V; $d = $b.Dim
    L "    // $N Inline Functions"
    L "    public static $N Union(in $N b1, in $N b2)"
    L '    {'
    L '        // Be careful to not run the two-point Bounds constructor.'
    L "        $N ret = default;"
    L '        ret.pMin = Min(b1.pMin, b2.pMin);'
    L '        ret.pMax = Max(b1.pMax, b2.pMax);'
    L '        return ret;'
    L '    }'
    L ''
    L "    public static $N Union(in $N b, $P p)"
    L '    {'
    L "        $N ret = default;"
    L '        ret.pMin = Min(b.pMin, p);'
    L '        ret.pMax = Max(b.pMax, p);'
    L '        return ret;'
    L '    }'
    L ''
    L "    public static $N Intersect(in $N b1, in $N b2)"
    L '    {'
    L "        $N b = default;"
    L '        b.pMin = Max(b1.pMin, b2.pMin);'
    L '        b.pMax = Min(b1.pMax, b2.pMax);'
    L '        return b;'
    L '    }'
    L ''
    L "    public static bool Overlaps(in $N ba, in $N bb) =>"
    L "        $(J $d '(ba.pMax.@ >= bb.pMin.@) && (ba.pMin.@ <= bb.pMax.@)' ' && ');"
    L ''
    L "    public static bool Inside($P p, in $N b) =>"
    L "        $(J $d 'p.@ >= b.pMin.@ && p.@ <= b.pMax.@' ' && ');"
    L ''
    if ($d -eq 2) {
        L "    public static bool Inside(in $N ba, in $N bb) =>"
        L "        $(J $d 'ba.pMin.@ >= bb.pMin.@ && ba.pMax.@ <= bb.pMax.@' ' && ');"
        L ''
    }
    L "    public static bool InsideExclusive($P p, in $N b) =>"
    L "        $(J $d 'p.@ >= b.pMin.@ && p.@ < b.pMax.@' ' && ');"
    L ''
    L "    public static $N Expand(in $N b, $T delta)"
    L '    {'
    L "        $N ret = default;"
    L "        ret.pMin = b.pMin - new $V($(J $d 'delta'));"
    L "        ret.pMax = b.pMax + new $V($(J $d 'delta'));"
    L '        return ret;'
    L '    }'
    L ''
}
L '}'

$text = $sb.ToString().Replace("`r`n", "`n")
[System.IO.File]::WriteAllText((Resolve-Path -LiteralPath (Split-Path $Out) | Join-Path -ChildPath (Split-Path $Out -Leaf)), $text)
Write-Host "Wrote $Out"
