#!/usr/bin/env python3
# Generates src/Pbrt.ImgTool/SkyModel/ArHosekSkyModelData.g.cs from
# pbrt-v4's src/ext/skymodel/ArHosekSkyModelData_Spectral.h (the only one of
# the Hosek-Wilkie datasets that imgtool's makesky uses).
#
# usage: python3 tools/gen-skymodel.py [path/to/pbrt-v4]
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
pbrt = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', 'pbrt-v4')
src = os.path.join(pbrt, 'src', 'ext', 'skymodel', 'ArHosekSkyModelData_Spectral.h')
dst = os.path.join(here, '..', 'src', 'Pbrt.ImgTool', 'SkyModel', 'ArHosekSkyModelData.g.cs')

text = open(src).read()
m = re.match(r'\s*(/\*.*?\*/)', text, re.S)
license = m.group(1)
body = text[m.end():]

# Strip the remaining C comments (the header describes the data layout in a
# second /* */ block; // comments label the albedo/turbidity blocks).
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
body = re.sub(r'//[^\n]*', '', body)

out = []
for name, init in re.findall(r'double\s*\*?\s*(\w+)\s*\[\]\s*=\s*\{(.*?)\}\s*;', body, re.S):
    items = [t.strip() for t in init.split(',') if t.strip()]
    if all(re.match(r'^[A-Za-z_]\w*$', t) for t in items):
        out.append(f'    public static readonly double[][] {name} = [{", ".join(items)}];')
    else:
        for t in items:
            float(t)  # sanity check: C and C# agree on these literals
        lines = []
        for i in range(0, len(items), 8):
            lines.append('        ' + ', '.join(items[i:i + 8]) + ',')
        out.append(f'    public static readonly double[] {name} =\n    [\n' + '\n'.join(lines) + '\n    ];')

with open(dst, 'w', newline='\n') as f:
    f.write('// <auto-generated> by tools/gen-skymodel.py from pbrt-v4\'s '
            'src/ext/skymodel/ArHosekSkyModelData_Spectral.h. Do not edit by hand. </auto-generated>\n\n')
    f.write(license + '\n\n')
    f.write('namespace Pbrt.ImgTool.SkyModel;\n\n')
    f.write('// The static readonly fields are initialized in textual order, so the\n')
    f.write('// per-wavelength tables come before the arrays that refer to them.\n')
    f.write('internal static class ArHosekSkyModelData\n{\n')
    f.write('\n\n'.join(out))
    f.write('\n}\n')
print(dst, len(out), 'arrays')
