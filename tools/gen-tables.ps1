# Converts pbrt-v4's numeric data tables (C++ array initializers) into C#
# source files in src/Pbrt/Util/*.g.cs.
#
#   util/primes.cpp        -> Primes.g.cs
#   util/sobolmatrices.cpp -> SobolMatrices.g.cs
#   util/spectrum.cpp      -> SpectrumData.g.cs (the spectral data tables)
#   util/bluenoise.cpp     -> ../Data/BlueNoise.bin (binary, see below)
#   util/pmj02tables.cpp   -> ../Data/PMJ02BN.bin (binary)
#
# Tables become `static ReadOnlySpan<T> Name => [...]` properties, which the
# C# compiler stores as constant data in the assembly (no allocation).
#
# Usage: pwsh tools/gen-tables.ps1 [-PbrtSrc ../pbrt-v4/src/pbrt]

param([string]$PbrtSrc = (Join-Path $PSScriptRoot '../../pbrt-v4/src/pbrt'))

$ErrorActionPreference = 'Stop'
$outDir = Join-Path $PSScriptRoot '../src/Pbrt/Util'

# Leading comment block (copyright/license) of a C++ source file.
function Get-HeaderComment([string[]]$lines) {
    $out = @()
    foreach ($l in $lines) {
        if ($l -match '^\s*//' -or $l -match '^\s*$') { $out += $l } else { break }
    }
    ($out -join "`n").TrimEnd()
}

# All integer literals (decimal or hex, with optional u/ULL suffix) in $text.
function Get-Numbers([string]$text) {
    [regex]::Matches($text, '\b(0x[0-9a-fA-F]+|\d+)(?:[uU]?[lL]{0,2})\b') | ForEach-Object { $_.Groups[1].Value }
}

# Formats values as C# collection-expression lines, $perLine per line.
function Format-Values([string[]]$values, [string]$suffix, [int]$perLine, [string]$indent = '        ',
                       [string]$prefix = '') {
    $sb = [System.Text.StringBuilder]::new()
    for ($i = 0; $i -lt $values.Count; $i += $perLine) {
        $chunk = $values[$i..([Math]::Min($i + $perLine, $values.Count) - 1)] | ForEach-Object {
            # A cast to an alias can't take a negative literal: -(Float)1, not (Float)-1.
            if ($prefix -ne '' -and $_.StartsWith('-')) { "-$prefix$($_.Substring(1))$suffix" } else { "$prefix$_$suffix" }
        }
        [void]$sb.Append($indent).Append($chunk -join ', ').AppendLine(',')
    }
    $sb.ToString().TrimEnd()
}

function Write-Generated([string]$name, [string]$text) {
    $path = Join-Path $outDir $name
    [System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($path), $text.Replace("`r`n", "`n"))
    Write-Host "Wrote $path"
}

$genNote = '// <auto-generated> by tools/gen-tables.ps1 from pbrt-v4 sources. Do not edit by hand. </auto-generated>'

# ---- primes.cpp ----
$src = Get-Content (Join-Path $PbrtSrc 'util/primes.cpp')
$text = ($src -join "`n")
$body = $text.Substring($text.IndexOf('Primes[PrimeTableSize] = {') + 'Primes[PrimeTableSize] = {'.Length)
$body = $body.Substring(0, $body.IndexOf('};'))
$body = ($body -split "`n" | Where-Object { $_ -notmatch '^\s*//' }) -join "`n"
$primes = @(Get-Numbers $body)
if ($primes.Count -ne 1000) { throw "Expected 1000 primes, got $($primes.Count)" }

Write-Generated 'Primes.g.cs' @"
$genNote
//
$(Get-HeaderComment $src)
//
// C# port of src/pbrt/util/primes.h and primes.cpp

namespace Pbrt;

public static partial class Util
{
    // Prime Table Declarations
    public const int PrimeTableSize = 1000;

    public static ReadOnlySpan<int> Primes =>
    [
$(Format-Values $primes '' 14)
    ];
}
"@

# ---- sobolmatrices.cpp ----
$src = Get-Content (Join-Path $PbrtSrc 'util/sobolmatrices.cpp')
$text = ($src -join "`n")

function Get-ArrayBody([string]$text, [string]$decl) {
    $start = $text.IndexOf($decl)
    if ($start -lt 0) { throw "Missing $decl" }
    $start = $text.IndexOf('{', $start + $decl.Length - 1)
    # Match braces to find the end of the initializer.
    $depth = 0
    for ($i = $start; $i -lt $text.Length; ++$i) {
        if ($text[$i] -eq '{') { ++$depth }
        elseif ($text[$i] -eq '}') { --$depth; if ($depth -eq 0) { return $text.Substring($start + 1, $i - $start - 1) } }
    }
    throw "Unterminated $decl"
}

$sobolSize = 52
$sobol32 = @(Get-Numbers (Get-ArrayBody $text 'SobolMatrices32[NSobolDimensions * SobolMatrixSize] ='))
if ($sobol32.Count -ne 1024 * $sobolSize) { throw "Unexpected SobolMatrices32 size $($sobol32.Count)" }

# VdC tables are [m][SobolMatrixSize] with rows given partially (rest zero);
# flatten to [m * SobolMatrixSize + c] with zero padding.
function Get-Rows([string]$body) {
    $rows = @()
    foreach ($m in [regex]::Matches($body, '\{([^{}]*)\}')) {
        $inner = ($m.Groups[1].Value -split "`n" | ForEach-Object { $_ -replace '//.*$', '' }) -join "`n"
        $vals = @(Get-Numbers $inner)
        if ($vals.Count -gt $sobolSize) { throw 'Row too long' }
        $rows += , ($vals + @('0') * ($sobolSize - $vals.Count))
    }
    , $rows
}
$vdc = Get-Rows (Get-ArrayBody $text 'VdCSobolMatrices[][SobolMatrixSize] =')
$vdcInv = Get-Rows (Get-ArrayBody $text 'VdCSobolMatricesInv[][SobolMatrixSize] =')
# (pbrt's VdCSobolMatricesInv has one more row than VdCSobolMatrices.)
$flatVdc = @($vdc | ForEach-Object { $_ })
$flatVdcInv = @($vdcInv | ForEach-Object { $_ })

Write-Generated 'SobolMatrices.g.cs' @"
$genNote
//
$(Get-HeaderComment $src)
//
// C# port of src/pbrt/util/sobolmatrices.h and sobolmatrices.cpp.
// VdCSobolMatrices[m][c] is VdCSobolMatrices[m * SobolMatrixSize + c] here.

namespace Pbrt;

public static partial class Util
{
    // Sobol Matrix Declarations
    public const int NSobolDimensions = 1024;
    public const int SobolMatrixSize = $sobolSize;
    public const int NVdCSobolMatrices = $($vdc.Count);
    public const int NVdCSobolMatricesInv = $($vdcInv.Count);

    public static ReadOnlySpan<uint> SobolMatrices32 =>
    [
$(Format-Values $sobol32 '' 6)
    ];

    public static ReadOnlySpan<ulong> VdCSobolMatrices =>
    [
$(Format-Values $flatVdc 'UL' 4)
    ];

    public static ReadOnlySpan<ulong> VdCSobolMatricesInv =>
    [
$(Format-Values $flatVdcInv 'UL' 4)
    ];
}
"@

# ---- spectrum.cpp ----
$src = Get-Content (Join-Path $PbrtSrc 'util/spectrum.cpp')
$text = ($src -join "`n")

# All floating-point literals in $text.
function Get-Floats([string]$text) {
    [regex]::Matches($text, '[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?') | ForEach-Object { $_.Value }
}

$expectedSizes = @{ nCIESamples = 471; nCIES = 107 }
$sb = [System.Text.StringBuilder]::new()
foreach ($m in [regex]::Matches($text, 'const Float (\w+)\[(\w*)\] =')) {
    $name = $m.Groups[1].Value
    $size = $m.Groups[2].Value
    $body = Get-ArrayBody $text $m.Value
    $body = ($body -split "`n" | ForEach-Object { $_ -replace '//.*$', '' }) -join "`n"
    $vals = @(Get-Floats $body)
    if ($size -ne '' -and $vals.Count -ne $expectedSizes[$size]) { throw "$name has $($vals.Count) values, expected $size" }
    if ($size -eq '' -and $vals.Count % 2 -ne 0) { throw "${name}: interleaved table with an odd number of values" }
    [void]$sb.AppendLine("    internal static ReadOnlySpan<Float> $name =>")
    [void]$sb.AppendLine('    [')
    # pbrt initializes these Float arrays from double literals; cast them
    # the same way so that they are doubles when Float is.
    [void]$sb.AppendLine((Format-Values $vals '' 6 -prefix '(Float)'))
    [void]$sb.AppendLine('    ];')
    [void]$sb.AppendLine()
}

Write-Generated 'SpectrumData.g.cs' @"
$genNote
//
$(Get-HeaderComment $src)
//
// C# port of the spectral data tables in src/pbrt/util/spectrum.cpp.
// Tables without a size are interleaved (lambda, value) pairs. The values
// are double literals cast to Float, as in pbrt.

namespace Pbrt;

public static partial class Spectra
{
    internal const int nCIESamples = $($expectedSizes.nCIESamples);
    internal const int nCIES = $($expectedSizes.nCIES);

$($sb.ToString().TrimEnd())
}
"@

# ---- bluenoise.cpp ----
# 786k values: as C# source this would add ~20s to every compile, so it is
# written as little-endian binary data that src/Pbrt embeds as a resource
# (loaded by Util/BlueNoise.cs).
$src = Get-Content (Join-Path $PbrtSrc 'util/bluenoise.cpp')
$text = ($src -join "`n")
$start = $text.IndexOf('PBRT_CONST uint16_t BlueNoiseTextures')
if ($start -lt 0) { throw 'Missing BlueNoiseTextures' }
$body = Get-ArrayBody $text.Substring($start) '[BlueNoiseResolution] ='
$noise = @(Get-Numbers $body)
if ($noise.Count -ne 48 * 128 * 128) { throw "Unexpected BlueNoiseTextures size $($noise.Count)" }

$bytes = [byte[]]::new(2 * $noise.Count)
for ($i = 0; $i -lt $noise.Count; ++$i) {
    $v = [int]$noise[$i]
    $bytes[2 * $i] = $v -band 0xff
    $bytes[2 * $i + 1] = $v -shr 8
}
$path = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../src/Pbrt/Data/BlueNoise.bin'))
[void][System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($path))
[System.IO.File]::WriteAllBytes($path, $bytes)
Write-Host "Wrote $path"

# ---- pmj02tables.cpp ----
# 655k uint32 values, written as little-endian binary like the blue noise
# (loaded by Util/PMJ02Tables.cs).
$src = Get-Content (Join-Path $PbrtSrc 'util/pmj02tables.cpp')
$text = ($src -join "`n")
$body = Get-ArrayBody $text 'pmj02bnSamples[nPMJ02bnSets][nPMJ02bnSamples][2] ='
$body = ($body -split "`n" | ForEach-Object { $_ -replace '//.*$', '' }) -join "`n"
$pmj = @(Get-Numbers $body)
if ($pmj.Count -ne 5 * 65536 * 2) { throw "Unexpected pmj02bnSamples size $($pmj.Count)" }

$bytes = [byte[]]::new(4 * $pmj.Count)
for ($i = 0; $i -lt $pmj.Count; ++$i) {
    $v = [uint32]$pmj[$i]
    $bytes[4 * $i] = $v -band 0xff
    $bytes[4 * $i + 1] = ($v -shr 8) -band 0xff
    $bytes[4 * $i + 2] = ($v -shr 16) -band 0xff
    $bytes[4 * $i + 3] = $v -shr 24
}
$path = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../src/Pbrt/Data/PMJ02BN.bin'))
[System.IO.File]::WriteAllBytes($path, $bytes)
Write-Host "Wrote $path"
